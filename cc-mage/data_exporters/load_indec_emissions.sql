 SELECT 
    emissions_id,
    datasource_name,
    actor_id,
    city_id,
    gpc_reference_number,
    emissions_value::numeric as emissions_value,
    emissions_year,
    'kg' as emissions_units,
    method_id as gpcmethod_id,
    upper(gas_name) as gas_name,
    emissionfactor_id,
    activity_id,
    activity_value,
    'city' as spatial_granularity,
    geometry_type,
    geometry,
    geometry_id
FROM raw_data.arg_solid_waste_indec
