    emissions_id,
    datasource_name,
    actor_id,
    city_id,
    gpc_reference_number,
    emissions_value,
    emissions_year,
    emissions_units,
    gpcmethod_id,
    gas_name,
    emissionfactor_id,
    activity_id,
    activity_value,
    spatial_granularity,
